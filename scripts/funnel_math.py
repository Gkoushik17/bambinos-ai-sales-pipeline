#!/usr/bin/env python3
"""Funnel math for Deliverable D. Every assumption is listed below; change them and re-run."""
from pathlib import Path

A = {
    "demos_per_week": 1000,
    "baseline_conv": 0.15,
    "lifts_pp": [0.02, 0.03],
    "counsellors": 40,
    "weeks_per_year": 52,
    # blended revenue per enrollment from catalog averages (6 courses) and an assumed geo mix
    "geo_mix": {"India": 0.70, "GCC": 0.15, "US/UK": 0.15},
    "avg_fee_inr": (9500 + 12000 + 13500 + 10500 + 9000 + 11000) / 6,
    "avg_fee_aed": (950 + 1200 + 1350 + 1200 + 990 + 1100) / 6,
    "avg_fee_usd": (225 + 265 + 295 + 250 + 265 + 245) / 6,
    "inr_per_aed": 22.9, "inr_per_usd": 88.0,
    # manager audit effort
    "call_minutes": 25, "manual_review_overhead_min": 10, "baseline_audit_rate": 0.02,
    "ai_flagged_share_for_review": 0.20, "ai_review_minutes": 6,
    # rep admin effort
    "rep_admin_min_saved_per_call": 6,  # CRM notes + drafting follow-ups
    # run cost
    "stt_usd_per_min": 0.006, "llm_usd_per_call": 0.10, "wa_msgs_per_lead": 3, "wa_inr_per_msg": 0.80,
    "infra_inr_per_week": 1200,
}

def inr(x):
    if x >= 1e7: return f"₹{x/1e7:.2f} Cr"
    if x >= 1e5: return f"₹{x/1e5:.2f} L"
    return f"₹{x:,.0f}"

aov_blend = (A["geo_mix"]["India"] * A["avg_fee_inr"] + A["geo_mix"]["GCC"] * A["avg_fee_aed"] * A["inr_per_aed"]
             + A["geo_mix"]["US/UK"] * A["avg_fee_usd"] * A["inr_per_usd"])
aov_cons = A["avg_fee_inr"]
base = A["demos_per_week"] * A["baseline_conv"]
calls = A["demos_per_week"]

out = ["# Funnel Math (generated by scripts/funnel_math.py)\n",
       f"- Baseline: {A['demos_per_week']:,} demos/week × {A['baseline_conv']:.0%} = **{base:.0f} enrollments/week**",
       f"- Revenue per enrollment: blended **{inr(aov_blend)}** (70% India / 15% GCC / 15% US-UK, catalog averages); conservative India-only **{inr(aov_cons)}**\n",
       "| Lift | Enrollments/wk | Extra/wk | Extra/yr | Extra revenue/yr (blended) | Extra revenue/yr (conservative) |",
       "|---|---|---|---|---|---|"]
for lp in A["lifts_pp"]:
    extra = A["demos_per_week"] * lp
    out.append(f"| +{lp*100:.0f} pp ({A['baseline_conv']*100:.0f}% → {(A['baseline_conv']+lp)*100:.0f}%) | {base+extra:.0f} | +{extra:.0f} | +{extra*A['weeks_per_year']:,.0f} | **{inr(extra*A['weeks_per_year']*aov_blend)}** | {inr(extra*A['weeks_per_year']*aov_cons)} |")

manual_now = calls * A["baseline_audit_rate"] * (A["call_minutes"] + A["manual_review_overhead_min"]) / 60
manual_full = calls * (A["call_minutes"] + A["manual_review_overhead_min"]) / 60
ai_review = calls * A["ai_flagged_share_for_review"] * A["ai_review_minutes"] / 60
rep_saved = calls * A["rep_admin_min_saved_per_call"] / 60
out += ["\n## Manager & rep hours",
        "| Item | Hours/week |", "|---|---|",
        f"| Today: manual audit of {A['baseline_audit_rate']:.0%} of calls ({calls*A['baseline_audit_rate']:.0f} calls × {A['call_minutes']+A['manual_review_overhead_min']} min) | {manual_now:.1f} |",
        f"| Manual effort needed for 100% coverage | {manual_full:.0f} (≈ {manual_full/40:.1f} FTE managers) |",
        f"| With AI: 100% audited, managers review only flagged {A['ai_flagged_share_for_review']:.0%} at {A['ai_review_minutes']} min | {ai_review:.0f} |",
        f"| **Manager hours saved vs. equivalent manual coverage** | **{manual_full-ai_review:.0f} hrs/week (≈ {(manual_full-ai_review)/40:.1f} FTE)** |",
        f"| Counsellor admin saved ({A['rep_admin_min_saved_per_call']} min/call on notes + follow-up drafting) | {rep_saved:.0f} hrs/week (≈ {rep_saved/A['counsellors']:.1f} hrs per rep) |"]

stt = calls * A["call_minutes"] * A["stt_usd_per_min"] * A["inr_per_usd"]
llm = calls * A["llm_usd_per_call"] * A["inr_per_usd"]
wa = calls * A["wa_msgs_per_lead"] * A["wa_inr_per_msg"]
cost = stt + llm + wa + A["infra_inr_per_week"]
low_rev = A["demos_per_week"] * A["lifts_pp"][0] * aov_blend
out += ["\n## Run cost & ROI",
        "| Cost item | ₹/week |", "|---|---|",
        f"| Speech-to-text ({A['call_minutes']} min/call) | {stt:,.0f} |",
        f"| LLM (audit + follow-up + safety check) | {llm:,.0f} |",
        f"| WhatsApp templates ({A['wa_msgs_per_lead']}/lead) | {wa:,.0f} |",
        f"| n8n / hosting | {A['infra_inr_per_week']:,} |",
        f"| **Total** | **{cost:,.0f}** (≈ {inr(cost*52)}/yr) |",
        f"\n- ROI at +2 pp: {low_rev/cost:.0f}× weekly cost. **Break-even = {cost/aov_blend:.1f} extra enrollments/week** (0.2 pp).",
        "- Not counted (upside): renewals after the 6-month term, recovered failed payments, refunds/chargebacks avoided through compliance, referrals."]

text = "\n".join(out) + "\n"
Path(__file__).resolve().parent.parent.joinpath("outputs", "final", "funnel_math.md").write_text(text)
print(text)
